%Reglas_lógicas
profesor_multiturno(Profe) :-
    materia(_, Profe, _, matutino, _),
    materia(_, Profe, _, vespertino, _).

profesor_carga_alta(Profe) :-
    materia(_, Profe, M1, _, G1),
    materia(_, Profe, M2, _, G2),
    materia(_, Profe, M3, _, G3),
    (M1 \= M2 ; G1 \= G2),
    (M1 \= M3 ; G1 \= G3),
    (M2 \= M3 ; G2 \= G3).

materia_interturno(Materia) :-
    materia(_, P1, Materia, matutino, _),
    materia(_, P2, Materia, vespertino, _),
    P1 \= P2.

profesor_multisemestre(Profe, Sem1, Sem2) :-
    materia(Sem1, Profe, M1, _, _),
    materia(Sem2, Profe, M2, _, _),
    Sem1 \= Sem2,
    M1 \= M2.

grupos_paralelos(Grupo1, Grupo2, Materia) :-
    materia(_, P1, Materia, Turno, Grupo1),
    materia(_, P2, Materia, Turno, Grupo2),
    Grupo1 \= Grupo2,
    P1 \= P2.

inconsistencia_grupo_turno(Profe, Materia, Turno, Grupo) :-
    materia(_, Profe, Materia, vespertino, Grupo),
    sub_string(Grupo, _, _, _, 'BM').

materia_unicodocente(Materia, Profe) :-
    materia(_, Profe, Materia, _, _),
    \+ (materia(_, OtroProfe, Materia, _, _), OtroProfe \= Profe).

profesor_area_gestion(Profe) :-
    materia(_, Profe, Materia, _, _),
    ( Materia = 'FUNDAMENTOS ECONOMICOS'
    ; Materia = 'FINANZAS EMPRESARIALES'
    ; Materia = 'INGENIERIA, ETICA Y SOCIEDAD'
    ; Materia = 'GESTION EMPRESARIAL'
    ; Materia = 'DESARROLLO DE HABILIDADES SOCIALES PARA LA ALTA DIRECCION'
    ).

grupo_solido(Semestre, Grupo) :-
    materia(Semestre, _, M1, _, Grupo),
    materia(Semestre, _, M2, _, Grupo), M1 \= M2,
    materia(Semestre, _, M3, _, Grupo), M1 \= M3, M2 \= M3,
    materia(Semestre, _, M4, _, Grupo), M1 \= M4, M2 \= M4, M3 \= M4.

profesor_multimateria(Profe, Materia1, Materia2) :-
    materia(_, Profe, Materia1, _, _),
    materia(_, Profe, Materia2, _, _),
    Materia1 \= Materia2.

%profesor_exclusivo_turno(Profe, Turno): El profesor imparte clases en un único turno (ej. solo matutino o solo vespertino).
profesor_exclusivo_turno(Profe, matutino) :-
    materia(_, Profe, _, matutino, _),
    \+ materia(_, Profe, _, vespertino, _).
profesor_exclusivo_turno(Profe, vespertino) :-
    materia(_, Profe, _, vespertino, _),
    \+ materia(_, Profe, _, matutino, _).

%materia_alta_demanda(Materia): Determina si una materia cuenta con más de 3 grupos o asignaciones registradas.
materia_alta_demanda(Materia) :-
    findall(G, materia(_, _, Materia, _, G), ListaGrupos),
    length(ListaGrupos, Cantidad),
    Cantidad > 3.

%profesor_multimateria(Profe, M1, M2): Encuentra profesores que imparten dos materias distintas.
profesor_multimateria(Profe, M1, M2) :-
    materia(_, Profe, M1, _, _),
    materia(_, Profe, M2, _, _),
    M1 \= M2.

%grupo_turno_matutino_puro(Grupo): Verifica si un grupo pertenece completamente al turno matutino revisando sus materias.
grupo_turno_matutino_puro(Grupo) :-
    materia(_, _, _, matutino, Grupo),
    \+ materia(_, _, _, vespertino, Grupo).

%colegas_mismo_semestre(Profe1, Profe2, Semestre): Encuentra dos profesores que dan clases en el mismo semestre.
colegas_mismo_semestre(Profe1, Profe2, Semestre) :-
    materia(Semestre, Profe1, _, _, _),
    materia(Semestre, Profe2, _, _, _),
    Profe1 \= Profe2.